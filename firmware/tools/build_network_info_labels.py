"""生成网络信息页的固定小字位图；不把完整字体放入固件。"""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, type=Path, help="支持中英文的字体文件")
    args = parser.parse_args()
    font = ImageFont.truetype(str(args.font), 12)
    target = Path(__file__).resolve().parents[1] / "src/network/NetworkInfoLabels.h"
    labels = {
        "kNetworkLabelsZh": ("控制台 http://", "同网浏览器打开"),
        "kPortalLabelsZh": ("控制台 http://", "先连配网热点"),
        "kNetworkLabelsEn": ("Console http://", "Same WiFi: browser"),
        "kPortalLabelsEn": ("Console http://", "Join setup WiFi"),
    }
    output = [
        "// Generated by firmware/tools/build_network_info_labels.py; do not edit.",
        "#pragma once", "#include <stdint.h>", "", "namespace tongdou {",
    ]
    for name, lines in labels.items():
        bitmap = Image.new("1", (128, 32))
        draw = ImageDraw.Draw(bitmap)
        for y, line in zip((0, 16), lines):
            box = draw.textbbox((0, 0), line, font=font)
            width, height = box[2] - box[0], box[3] - box[1]
            if width > 128 or height > 16:
                raise ValueError(f"文字超出屏幕: {line}")
            draw.text(((128 - width) // 2 - box[0], y - box[1]), line, font=font, fill=1)
        data = [
            sum((1 << bit) for bit in range(8) if bitmap.getpixel((x, page * 8 + bit)))
            for page in range(4) for x in range(128)
        ]
        output.append(f"constexpr uint8_t {name}[512] = {{")
        for start in range(0, len(data), 16):
            output.append("  " + ", ".join(f"0x{v:02x}" for v in data[start:start + 16]) + ",")
        output.append("};")
    output.append("}  // namespace tongdou\n")
    target.write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
